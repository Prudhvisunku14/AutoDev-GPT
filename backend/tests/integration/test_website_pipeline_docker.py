"""Opt-in (RUN_DOCKER_TESTS=true): the website pipeline through the real orchestrator with the REAL website verifier.

GPT and the coding provider are scripted (app/demo/website.py), so nothing is generated by a model and nothing is spent. The
verification is real: each submitted candidate is copied into a disposable folder, served by DevPilot's server in the
hardened no-network container, rendered in Chromium, and judged by the run's frozen browser checks. The first candidate's
form accepts anything, so AC-003 must fail in the browser; the repair restores validation, so the second run must pass.

The verifier image must be present (`devpilot setup --web` builds and self-tests it). This test approves the image's current
ID for its own process only, as `setup --web` would after its self-test; it grants no approval outside the test.
"""

from __future__ import annotations

from collections.abc import Iterator
from pathlib import Path

import pytest

from app.core.egress import EgressPolicy
from app.db.models import RunState
from app.demo import website
from app.verification import recipes, web
from tests.unit.test_acceptance_flow import Seeing
from tests.unit.test_coding_tools import Rig


@pytest.fixture
def real_verifier(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Iterator[web.WebVerifier]:
    verifier = web.WebVerifier(EgressPolicy({"sandbox_install": ["registry.npmjs.org"]}), work_dir=tmp_path / "web", timeout=240)
    try:
        image_id = verifier.image_id()
    except web.WebVerificationError as exc:
        pytest.skip(str(exc))
    web.approve_locally(image_id)
    if not recipes.WEB_ENGINE_WIRED:
        monkeypatch.setattr(recipes, "WEB_ENGINE_WIRED", True)
    yield verifier
    web._APPROVED.clear()


@pytest.mark.docker
def test_the_website_pipeline_with_real_browser_acceptance_repairs_and_delivers(tmp_path: Path, real_verifier: web.WebVerifier) -> None:
    r = Rig(tmp_path, *website.gpt_script(), launcher=Seeing([website.FIRST_ATTEMPT, website.REPAIR_ATTEMPT]), web=real_verifier)
    final = r.advance()
    report = r.report()
    sites = report["website_verifications"]
    assert final.state is RunState.COMPLETED, (final.outcome, final.status_detail, [s["reason"] for s in sites])
    assert [s["verdict"] for s in sites] == ["FAILED", "PASSED"] and all(s["cleanup"] == "removed" for s in sites)
    first, second = sites
    assert [a["id"] for a in first["acceptance"] if not a["ok"]] == ["AC-003"]  # caught in Chromium, not by a stand-in
    assert all(a["ok"] for a in second["acceptance"]) and len(second["acceptance"]) == 4
    assert any(s["name"] == "browser" and s["ok"] for s in second["stages"])
    independent = report["acceptance"]
    assert independent["kind"] == "browser" and independent["verdict"] == "PASSED" and report["run"]["repairs"] == 1
    assert website.REPAIR_ATTEMPT.files["app.js"] == r.h.workspace.read_text(r.project_id, "app.js")
