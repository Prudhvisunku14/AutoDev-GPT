import { useState } from "react";
import { useApi } from "../lib/apiContext";
import { useArtifact } from "../lib/queries";
import type { Run } from "../lib/types";

/** Explicit GitHub write consent. Never publishes without a verified delivery and two-step confirmation. */
export function GitHubPublishCard({ run }: { run: Run }) {
  const api = useApi();
  const artifact = useArtifact(run);
  const [repository, setRepository] = useState("");
  const [base, setBase] = useState("main");
  const [branch, setBranch] = useState(`devpilot/${run.id.slice(0, 10)}`);
  const [title, setTitle] = useState("DevPilot verified implementation");
  const [preview, setPreview] = useState<Awaited<ReturnType<typeof api.previewGithubPR>> | null>(null);
  const [confirmation, setConfirmation] = useState("");
  const [result, setResult] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  if (!artifact.data?.available) return null;

  async function prepare() {
    setBusy(true);
    setError(null);
    setPreview(null);
    setResult(null);
    try {
      const item = await api.previewGithubPR({ run_id: run.id, repository, base, branch, title, body: "Generated by DevPilot. Files passed the recorded verification gates. Review this draft before merging." });
      setPreview(item);
      setConfirmation("");
    } catch (e) {
      setError(e instanceof Error ? e.message : "GitHub preview failed");
    } finally { setBusy(false); }
  }

  async function publish() {
    if (!preview || confirmation !== preview.confirmation_required) return;
    setBusy(true);
    setError(null);
    try {
      const item = await api.publishGithubPR(preview.preview_id, confirmation);
      setResult(item.url);
      setPreview(null);
    } catch (e) {
      setError(e instanceof Error ? e.message : "GitHub could not create the draft PR; check for a partially created branch");
      setPreview(null);
    } finally { setBusy(false); }
  }

  return (
    <section className="mt-4 rounded-2xl border border-line bg-white p-5" aria-label="Publish a GitHub draft pull request">
      <h2 className="text-base font-semibold">Create a draft GitHub pull request</h2>
      <p className="mt-1 text-xs text-muted">Only files from this verified delivery are eligible. No merge, deploy or force-push is performed. Publishing needs your typed confirmation and your GitHub connection (Tools page); the backend keeps the token.</p>
      <div className="mt-3 grid gap-2 sm:grid-cols-2">
        <label className="text-sm">Repository (owner/name)<input value={repository} onChange={(e) => { setRepository(e.target.value); setPreview(null); }} className="mt-1 w-full rounded-lg border p-2" placeholder="owner/repository" /></label>
        <label className="text-sm">Base branch<input value={base} onChange={(e) => { setBase(e.target.value); setPreview(null); }} className="mt-1 w-full rounded-lg border p-2" /></label>
        <label className="text-sm">New branch<input value={branch} onChange={(e) => { setBranch(e.target.value); setPreview(null); }} className="mt-1 w-full rounded-lg border p-2" /></label>
        <label className="text-sm">PR title<input value={title} onChange={(e) => { setTitle(e.target.value); setPreview(null); }} className="mt-1 w-full rounded-lg border p-2" /></label>
      </div>
      <button type="button" onClick={() => void prepare()} disabled={busy || !repository.includes("/")} className="mt-3 rounded-lg bg-violet-700 px-4 py-2 text-sm font-semibold text-white disabled:opacity-50">Preview GitHub changes</button>
      {preview && <div className="mt-3 rounded-xl border p-3 text-sm">
        <p className="font-semibold">Review the exact upload before allowing a GitHub write</p>
        <p>{preview.preview.repository} → {preview.preview.branch} · {preview.preview.files.length} files · {preview.preview.total_bytes} bytes · {preview.verification_level} verification</p>
        <p className="text-xs text-muted">{preview.github_account ? `As GitHub account ${preview.github_account}` : "GitHub is not connected: connect it on the Tools page before publishing"}</p>
        <ul className="mt-2 max-h-36 overflow-y-auto text-xs">{preview.preview.files.map(f => <li key={f.path}>{f.path} ({f.bytes} bytes)</li>)}</ul>
        <label className="mt-3 block text-xs">Type <strong>{preview.confirmation_required}</strong> to publish<input value={confirmation} onChange={e => setConfirmation(e.target.value)} className="mt-1 w-full rounded-lg border p-2" /></label>
        <button type="button" disabled={busy || confirmation !== preview.confirmation_required} onClick={() => void publish()} className="mt-2 rounded-lg bg-slate-900 px-4 py-2 text-sm font-semibold text-white disabled:opacity-50">Create draft PR (GitHub write)</button>
      </div>}
      {result && <p className="mt-3 text-sm">Draft pull request: <a href={result} target="_blank" rel="noreferrer" className="font-medium text-violet-700 underline">View on GitHub</a></p>}
      {error && <p role="alert" className="mt-3 text-xs text-red-700">{error}</p>}
    </section>
  );
}
